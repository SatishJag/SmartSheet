"""
Generates the Data centre master schedule catalog from the owner's workbook
("DC Integrated Project Schedule Reference Template", sheet "DC Master Schedule"):

  src/planner/catalogs/dcMaster.ts       the source of truth (typed module)
  supabase/migrations/0023_dc_master.sql the seed (src/db/dcMaster.test.ts checks the two agree)

Usage (the workbook is untrusted input; run isolated):  python3 -I scripts/gen-dc-master.py <workbook.xlsx>
The workbook itself is not committed. Spec: docs/superpowers/specs/2026-11-22-full-plan-design.md
"""
import json
import pathlib
import sys

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGES = ['Power Modules', 'Generator Sets', 'Transformers', 'Chillers', 'Switchgear', 'Fan Wall Units (FWU)']
# Columns (0-based) of the "DC Master Schedule" sheet; the heading row is 7.
STAGE, ID, NAME, KIND, LEAD, SYSTEM, DURATION = 1, 2, 3, 4, 5, 6, 8
PREDECESSORS = [(9, 10, 11), (12, 13, 14), (15, 16, 17)]
CRITERIA = 26

TYPE = {
    'id': 'dc-master',
    'name': 'Data centre master schedule',
    'description': 'The full data centre project from the reference template: strategy, feasibility, design, permits, funding, long-lead equipment, construction, commissioning levels 1 to 5, Ready for Service and close-out. Planned back from the RFS date on a 7-day week; long-lead packages use real history where it exists.',
    'itemLabels': {
        'noun': 'plan',
        'typeExample': 'Data centre',
        'nameExample': 'Bangkok 3',
        'heading': 'Which data centre are you planning?',
        'intro': 'Choose the project and its Ready for Service date. The full plan is built backward from that date.',
        'dateLabel': 'RFS date',
    },
    'targetId': 'DC-0192',
}


def text(v):
    return '' if v is None else ' '.join(str(v).split())


def whole(v, what):
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    if not isinstance(v, int):
        raise SystemExit(f'{what} is not a whole number: {v!r}')
    return v


def read(path):
    ws = openpyxl.load_workbook(path, data_only=False)['DC Master Schedule']
    heading = [text(c) for c in next(ws.iter_rows(min_row=7, max_row=7, values_only=True))]
    assert heading[ID] == 'Activity ID' and heading[CRITERIA].startswith('Completion'), heading
    acts, steps = [], {p: 0 for p in PACKAGES}
    for r in ws.iter_rows(min_row=8, values_only=True):
        if not r[ID]:
            continue
        aid = text(r[ID])
        milestone = text(r[KIND]) == 'Milestone'
        days = 0 if milestone else whole(r[DURATION], f'{aid} duration')
        links = []
        for p, rel, lag in PREDECESSORS:
            if r[p]:
                links.append({'from': text(r[p]).replace('-', '_'), 'type': text(r[rel]) or 'FS', 'lagDays': whole(r[lag] or 0, f'{aid} lag')})
        act = {
            'code': aid.replace('-', '_'),
            'id': aid,
            'stage': text(r[STAGE]),
            'name': text(r[NAME]),
            'milestone': milestone,
            'responsibility': text(r[LEAD]),
            'criteria': text(r[CRITERIA]),
            'defaultDays': days,
            'links': links,
        }
        package = text(r[SYSTEM])
        if package in PACKAGES:
            steps[package] += 1
            act['package'] = package
            act['step'] = steps[package]
        acts.append(act)
    return acts


def ts(acts):
    def obj(a):
        lines = [f'    {k}: {json.dumps(a[k], ensure_ascii=False)},' for k in ('code', 'id', 'stage', 'name', 'milestone', 'responsibility', 'criteria', 'defaultDays')]
        links = ', '.join('{ from: %s, type: %s, lagDays: %d }' % (json.dumps(l['from']), json.dumps(l['type']), l['lagDays']) for l in a['links'])
        lines.append(f'    links: [{links}],')
        if 'package' in a:
            lines.append(f'    package: {json.dumps(a["package"])},')
            lines.append(f'    step: {a["step"]},')
        return '  {\n' + '\n'.join(lines) + '\n  },'

    t = TYPE
    return f'''/**
 * Data centre master schedule: the owner's "DC Integrated Project Schedule Reference Template" (sheet
 * "DC Master Schedule") as the catalog of the Plan with AI schedule type `dc-master`.
 * (docs/superpowers/specs/2026-11-22-full-plan-design.md)
 *
 * GENERATED by scripts/gen-dc-master.py from the workbook; do not edit by hand. The seed
 * supabase/migrations/0023_dc_master.sql is generated alongside, and src/db/dcMaster.test.ts checks the two
 * agree.
 *
 * Durations and lags are the template's CALENDAR days (the plan runs on a 7-day week). Codes are the
 * template's activity ids with "_" for "-" (catalog codes allow capitals, digits and "_"); `id` keeps the
 * template's form for the Activity ID column. The six long-lead packages are marked with their step
 * (1-9, template order); src/planner/catalogs/dcPackages.ts maps them to history and cost codes.
 */
import type {{ ItemLabels }} from '../types'

export type DcPackage = {' | '.join(json.dumps(p) for p in PACKAGES)}

export interface DcActivity {{
  /** Catalog code, e.g. "DC_0055". */
  code: string
  /** The template's activity id, e.g. "DC-0055". */
  id: string
  /** Stage / workstream, e.g. "07 LLE Cat A vendor procurement & delivery". */
  stage: string
  name: string
  milestone: boolean
  responsibility: string
  criteria: string
  /** Template duration in calendar days (0 for milestones). */
  defaultDays: number
  /** Predecessors by code; lags in calendar days. */
  links: {{ from: string; type: 'FS' | 'SS' | 'FF' | 'SF'; lagDays: number }}[]
  /** The long-lead package this activity belongs to, and its step (1-9) in it. */
  package?: DcPackage
  step?: number
}}

export const DC_MASTER_TYPE = {{
  id: 'dc-master',
  name: {json.dumps(t['name'])},
  description: {json.dumps(t['description'], ensure_ascii=False)},
  position: 0,
  projectTypes: ['data-centre'],
  itemLabels: {json.dumps(t['itemLabels'])} satisfies ItemLabels,
  targetId: 'DC-0192',
  targetCode: 'DC_0192',
}} as const

export const DC_MASTER_ACTIVITIES: DcActivity[] = [
{chr(10).join(obj(a) for a in acts)}
]
'''


def sql_text(s):
    return "'" + s.replace("'", "''") + "'"


def sql(acts):
    t = TYPE
    rows = []
    for i, a in enumerate(acts, 1):
        links = json.dumps([{'from': l['from'], 'type': l['type'], 'lagDays': l['lagDays']} for l in a['links']], separators=(',', ':'))
        rows.append('  (' + ', '.join([
            "'dc-master'", sql_text(a['code']), sql_text(a['name']), sql_text(a['stage']), str(i), sql_text(links), str(a['defaultDays']),
            'true' if a['id'] == t['targetId'] else 'false', sql_text(a['id']), sql_text(a['responsibility']), sql_text(a['criteria']),
        ]) + ')')
    return f'''-- Plan with AI: the Data centre master schedule as a schedule type (`dc-master`, project type Data
-- centre), offered in the wizard as "All (full project plan)". GENERATED by scripts/gen-dc-master.py from
-- the owner's "DC Integrated Project Schedule Reference Template"; the source of truth is
-- src/planner/catalogs/dcMaster.ts and src/db/dcMaster.test.ts checks that this seed and the module agree.
-- (docs/superpowers/specs/2026-11-22-full-plan-design.md)
--
-- default_days and lags are the template's CALENDAR days: the plan runs on a 7-day week. The target is
-- DC-0192 "READY FOR SERVICE (RFS)"; taking-over, handover and close-out keep the template's own logic.
-- Codes are the template ids with "_" for "-"; activity_id keeps the template's form.

insert into schedule_types (id, name, description, position, project_types, item_labels) values
  ('dc-master', {sql_text(t['name'])}, {sql_text(t['description'])}, 0, '{{data-centre}}', {sql_text(json.dumps(t['itemLabels'], separators=(',', ':')))});

insert into activity_catalog (schedule_type, code, name, phase, sequence, default_links, default_days, is_target, activity_id, responsibility, criteria) values
{(','+chr(10)).join(rows)};
'''


def main():
    acts = read(sys.argv[1])
    (ROOT / 'src/planner/catalogs/dcMaster.ts').write_text(ts(acts), encoding='utf-8')
    (ROOT / 'supabase/migrations/0023_dc_master.sql').write_text(sql(acts), encoding='utf-8')
    print(f'{len(acts)} activities, {sum(len(a["links"]) for a in acts)} links')


if __name__ == '__main__':
    main()
