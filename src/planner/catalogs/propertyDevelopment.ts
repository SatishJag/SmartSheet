/**
 * Property development master schedule: the reference template of the Property department
 * ("Property Development Project Schedule Template", sheets "Schedule Template" and "Basis of Plan"),
 * as the catalog of the "Plan with AI" schedule type `property-development`.
 *
 * This module is the source of truth: supabase/migrations/0018_property_development.sql seeds the same
 * activities (src/db/propertyDevelopment.test.ts checks the two agree). Activity ids, stages (WBS),
 * names, lead responsibility, the reference logic (FS / SS, no lags) and the completion / release
 * criteria are the template's own. GENERATED by a script from the workbook; edit with care.
 *
 * PLACEHOLDER DEFAULT DURATIONS: the template deliberately imposes no durations ("No generic project
 * duration or historic dates have been imposed"). The planner needs a fallback per activity, so the
 * working days below are representative figures for a mid-size residential or mixed-use development.
 * They are used only until history for this schedule type is loaded, and the AI is told to adapt them
 * to the project described. Milestones are always 0.
 *
 * The target (the date the planner asks for) is P420 "Complete planned handover". The defects period
 * and close-out (P430, P440) follow it, as in the template.
 */

